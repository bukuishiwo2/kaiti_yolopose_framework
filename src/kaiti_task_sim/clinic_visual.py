"""Visual evidence adapter and finite Clinic compiler; one protocol owner.

No model labels or verification verdicts are invented here. Navigation approval
is a separate, fail-closed gate, not inferred from a free map pixel.
"""
from copy import deepcopy
import hashlib
import json
import math

from .event_protocol import EventTaskProtocol, ProtocolError, canonical


def action_uuid_bytes(values):
    """ROS Humble UUID arrays can contain numpy.uint8; log plain JSON ints."""
    result = [int(v) for v in values]
    if len(result) != 16 or any(v < 0 or v > 255 for v in result):
        raise ValueError('invalid ROS action UUID')
    return result


def region_registry(config):
    """Reuse existing anchors/travel/resource phases, without editing Clinic."""
    return {
        'A': dict(event_xy=config['event']['center'],
                  anchors=dict(verify='V1', monitor='M1', deliver='H1')),
        'B': dict(event_xy=[22.0, -20.0],
                  anchors=dict(verify='DL', monitor='CDL', deliver='ADL')),
    }


def registered_space(config, region, valid=True):
    r = region_registry(config)[region]
    return dict(valid=valid, frame='map', event_xy=list(r['event_xy']),
                provenance='video_source_registered', registration_id=region,
                service_points={role: config['anchors'][a][:2]
                                for role, a in r['anchors'].items()},
                sensor_estimate=None)


class VisualEventBridge:
    """A stable model candidate authorizes VERIFY only, never a fall verdict.

    source_id identifies the registered video observation episode, not a
    cross-camera person identity. Replays retain that identity and reset the
    model separately. No new observations are generated by tick().
    """
    def __init__(self, config, region='A', source_id='urfall', ttl=10., max_age=1., protocol_type=EventTaskProtocol):
        self.config, self.region, self.source_id = config, region, source_id
        self.protocol = protocol_type(position_ttl=ttl, supply=config['anchors']['G1'][:2])
        self.max_age = max_age
        self.samples = set()
        self.evidence = []
        self.counter = 0

    def tick(self, now):
        self.counter += 1
        return self.protocol.apply(dict(schema='event-task/v1', kind='tick',
            message_id=f'clock:{self.counter}', at=now))

    def observe(self, sample, now, space_valid=True):
        required = ('sample_id', 'source_id', 'source_at', 'score', 'stable', 'window_ready')
        if any(k not in sample for k in required):
            raise ValueError('incomplete model evidence')
        if sample['source_id'] != self.source_id:
            raise ValueError('source identity mismatch; no unsupported multi-source fusion')
        if not math.isfinite(sample['score']) or not 0 <= sample['score'] <= 1:
            raise ValueError('invalid model score')
        source_at = sample['source_at']
        if not math.isfinite(source_at) or not 0 <= now-source_at <= self.max_age:
            return dict(decision='STALE_OR_FUTURE_MODEL_EVIDENCE')
        if sample['sample_id'] in self.samples:
            return dict(decision='DUPLICATE_MODEL_SAMPLE')
        self.samples.add(sample['sample_id'])
        self.evidence.append(deepcopy(sample))
        positive = sample['stable'] is True and sample['window_ready'] is True
        if not positive and self.protocol.event is None:
            return self.tick(now)
        msg = dict(schema='event-task/v1', kind='observation',
            message_id='image:'+sample['sample_id'], event_id='E1',
            at=now, source_at=source_at, status='confirmed' if positive else 'occluded')
        if positive:
            msg['space'] = registered_space(self.config, self.region, space_valid)
        result = self.protocol.apply(msg)
        result['evidence'] = dict(sample_id=sample['sample_id'], score=sample['score'],
            stable=sample['stable'], source_id=self.source_id,
            meaning='stable_model_candidate_not_service_verdict',
            observation_state='positive' if positive else 'no_positive_evidence')
        return result

    def feedback(self, message, verdict=None):
        """ACK tokens come from executor; verdict has separate explicit provenance."""
        msg = deepcopy(message)
        task = self.protocol.tasks.get(msg.get('task_id'), {})
        if task.get('role') == 'verify' and msg.get('phase') == 'succeeded':
            if not verdict or verdict.get('result') not in {'fall', 'no_fall'}:
                raise ProtocolError('service success is not a verification verdict')
            if verdict.get('source') not in {'operator_review', 'independent_sensor_review', 'controlled_visual_review'}:
                raise ProtocolError('explicit review source required')
            if not verdict.get('evidence_id') or verdict.get('event_id') != 'E1':
                raise ProtocolError('verdict must identify event and reviewed evidence')
            msg['result'] = verdict['result']
        elif 'result' in msg:
            raise ProtocolError('unexpected service verdict')
        return self.protocol.apply(msg)


def compile_tasks(view, now, config, region, phases, navigation_certificate=None):
    """Replace the fixed-V1 compiler only in the explicit visual mode.

    Uses existing phase expansion and exact anchor travel tables. Requires an
    exact target match; arbitrary coordinates do not fall back to V1.
    """
    mapping = dict(region_registry(config)[region]['anchors'], pickup='G1')
    result = {}
    for task in view['tasks']:
        role = task['role']
        a = mapping[role]
        if task['target']['frame'] != 'map' or task['target']['xy'] != config['anchors'][a][:2]:
            raise ValueError('target/region mismatch; revalidate registration before compilation')
        resources = [a] if a in config['resource_phases'] else []
        item = dict(kind=role, anchor=a,
            duration=None if role == 'monitor' else dict(verify=3., pickup=8., deliver=6.)[role],
            release=now, deadline=1800., capabilities=task['capabilities'], resources=resources,
            dependencies=['E1_'+d.split(':')[1] for d in task['completion_dependencies']],
            protocol_task_id=task['task_id'], protocol_revision=task['revision'],
            protocol_attempt=task['attempt'], service_role=role, energy_rate=0.,
            spatial_source='video_source_registered', region=region,
            execution_authorized=False)
        if role == 'monitor':
            item.update(minimum_duration=2., start_deadline=now+360.)
        if role == 'verify':
            item['start_deadline'] = now+360.
        if role in {'pickup', 'deliver'}:
            item.update(cargo_role='pickup' if role == 'pickup' else 'drop', cargo_group='E1')
        item = phases(item, config)
        assert item['location'] == task['target']['xy']
        if navigation_certificate:
            digest = hashlib.sha256(canonical(config).encode()).hexdigest()
            item['execution_authorized'] = (
                navigation_certificate.get('passed') is True and
                navigation_certificate.get('region') == region and
                navigation_certificate.get('config_sha256') == digest and
                role in navigation_certificate.get('qualified_roles', []) and
                (navigation_certificate.get('concurrent_resource_qualification') is True or
                 (role == 'verify' and 'verify' in navigation_certificate.get('qualified_roles', []))) and
                {item['anchor'], item['entry_anchor'], item['clear_anchor']}.issubset(
                    navigation_certificate.get('validated_anchors', []))
            )
        result['E1_'+role] = item
    return result


def execution_fence(protocol, tokens):
    """Fence solver commits against task identity, not observation heartbeats."""
    errors = []
    if tokens and (not protocol.event or not protocol.event.get('position_valid')):
        errors.append('position_invalid_or_expired')
    for task_id, expected in tokens.items():
        task = protocol.tasks.get(task_id)
        actual = None if task is None else {k: deepcopy(task.get(k))
            for k in ('revision', 'attempt', 'target', 'required_owner')}
        if actual != expected or task['state'] not in {'READY', 'PENDING'}:
            errors.append(task_id)
    return dict(passed=not errors, errors=errors)


def execution_tokens(protocol, task_ids):
    return {task_id: {k: deepcopy(protocol.tasks[task_id].get(k))
        for k in ('revision', 'attempt', 'target', 'required_owner')} for task_id in task_ids}


def transfer_guard(snapshot, role, proposed_owner=None, cancel_ack=False, handover_ack=False):
    """Fail closed before releasing a service commitment or cargo ownership.

    This guard never manufactures a cancellation ACK. A real executor must
    supply it, and active monitor release additionally needs delivery/handover.
    """
    task = snapshot['tasks'].get('E1:'+role, {})
    event = snapshot.get('event') or {}
    if role == 'monitor' and task.get('state') in {'RUNNING', 'CANCEL_REQUESTED'}:
        delivered = snapshot['tasks'].get('E1:deliver', {}).get('state') == 'SUCCEEDED'
        if not (delivered and handover_ack):
            return dict(allowed=False, reason='ACTIVE_MONITOR_REQUIRES_DELIVERY_HANDOVER')
    if role in {'pickup', 'deliver'} and event.get('cargo_owner') and event.get('cargo_disposition') != 'DELIVERED':
        if proposed_owner != event['cargo_owner']:
            return dict(allowed=False, reason='CARGO_OWNER_PROTECTED')
    if task.get('state') in {'RUNNING', 'CANCEL_REQUESTED'} and not cancel_ack:
        return dict(allowed=False, reason='EXECUTION_ACK_REQUIRED')
    return dict(allowed=True, reason='NO_UNRELEASED_COMMITMENT')


def sensor_position_contract():
    """Independent RGB-D branch; no registration masquerading as estimation."""
    return dict(schema='human-spatial-evidence/v1', provenance='sensor_estimated',
        identity=dict(source_id=None, track_id=None, association_evidence=None),
        rgb_stamp=None, depth_stamp=None, camera_info_stamp=None, tf_stamp=None,
        camera_frame=None, map_frame='map', camera_intrinsics=None,
        depth_encoding=None, depth_unit_m=None, map_xyz=None,
        valid=False, invalid_reason='NOT_OBSERVED',
        error=dict(covariance=None, ground_truth_error_m=None, evaluation_only=True))


def visual_obstacle(snapshot, previous_xy):
    """A candidate alone does not assert a confirmed fallen-body footprint."""
    e=snapshot.get('event')
    if not e:return False,previous_xy
    active=e.get('verified') is True and e.get('lifecycle') not in {'CLOSED','COMPLETED'}
    space=e.get('space') or {}
    xy=space.get('event_xy')
    if space.get('valid') and space.get('frame')=='map' and isinstance(xy,list) and len(xy)==2 and all(isinstance(v,(int,float)) and math.isfinite(v) for v in xy):
        return active,xy[:]
    return active,previous_xy  # occlusion does not silently remove confirmed body
